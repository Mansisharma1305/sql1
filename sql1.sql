-- Task 6: Sales Trend Analysis Using Aggregations

-- a. Use EXTRACT(MONTH FROM order_date) for month

SELECT EXTRACT(MONTH FROM InvoiceDate) AS Month FROM saledata;


-- | InvoiceDate           | Month |
-- |-----------------------|-------|
-- | 2020-01-01 00:00:00   | 1     |
-- | 2020-01-01 01:00:00   | 1     |
-- | 2020-01-01 02:00:00   | 1     |
-- | 2020-01-01 03:00:00   | 1     |
-- | 2020-01-01 05:00:00   | 1     |

-- b. GROUP BY year/month

SELECT EXTRACT(YEAR FROM InvoiceDate) AS Year, EXTRACT(MONTH FROM InvoiceDate) AS Month
FROM saledata
GROUP BY Year, Month;

-- c. Use SUM() for revenue

-- d. COUNT(DISTINCT order_id) for volume

SELECT
    EXTRACT(YEAR FROM InvoiceDate) AS Year,
    EXTRACT(MONTH FROM InvoiceDate) AS Month,
    ROUND(SUM(UnitPrice * Quantity), 2) AS TotalRevenue,
    COUNT(DISTINCT InvoiceNo) AS OrderVolume
FROM saledata
WHERE Quantity > 0 AND UnitPrice > 0
GROUP BY Year, Month
ORDER BY Year, Month;

